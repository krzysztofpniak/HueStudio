const a = $.TypeVariable('a');
const b = $.TypeVariable('b');
const c = $.TypeVariable('c');

const f = $.UnaryTypeVariable('f');

const cond = def('cond')({})([
  $.Array($.Array2($.Function([a, $.Boolean]))($.Function([a, b]))),
  a,
  $.Maybe(b)
])(conds => a => map(x => x[1](a))(find(x => x[0](a))(conds)));

const cond2 = def('cond2')({})([
  $.Array($.Array2($.Function([a, b, $.Boolean]))($.Function([a, b, c]))),
  a,
  b,
  c
])(conds => a => b =>
  fromMaybe_(() => {
    throw 'kupa';
  })(map(x => x[1](a)(b))(find(x => x[0](a)(b))(conds)))
);

const assoc = def('assoc')({})([$.String, a, $.StrMap(a), $.StrMap(a)])(
  key => value => target => ({ ...target, [key]: value })
);

const renameKeys = def('renameKeys')({})([
  $.StrMap($.String),
  $.StrMap(a),
  $.StrMap(a)
])(keysMap => obj =>
  reduce(acc => key => assoc(keysMap[key] || key)(obj[key])(acc))({})(keys(obj))
);

const reduceIndexed = def('reduceIndexed')({ f: [Z.Foldable] })([
  $.Fn(a)($.Fn(b)($.Fn(c)(a))),
  a,
  f(b),
  a
])(fn => initial => data => {
  let idx = 0;
  return reduce(p => c => fn(p)(c)(idx++))(initial)(data);
});

